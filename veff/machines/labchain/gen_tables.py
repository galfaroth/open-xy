#!/usr/bin/env python3
# Generates tables.h: the constant curves Lab Chain's integer DSP reads.
# The same formulas as veffbox's tools/gen_tables.py (the FX subset), plus the
# exp2 and tan tables veffbox kept inline in vb_fx.c.
#   python3 gen_tables.py > tables.h
import math

SR = 44100


def row(vals, per=12):
    return "\n".join("    " + ", ".join(str(v) for v in vals[i:i + per]) + ","
                     for i in range(0, len(vals), per))


def table(kind, name, vals, per=12, comment=None):
    if comment:
        print(f"// {comment}")
    print(f"const {kind} {name}[{len(vals)}] = {{\n{row(vals, per)}\n}};\n")


def main():
    print("// Generated by gen_tables.py. Do not edit.")
    print("#pragma once")
    print("#include <opxy/types.hpp>\n")
    print("namespace labchain { namespace tables {")
    print("using opxy::i16; using opxy::i32; using opxy::u32;\n")
    table("i16", "sine", [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)],
          comment="One sine cycle, Q15, 1024 points and a guard point")
    table("i16", "tanh", [round(32767 * math.tanh(-4 + 8 * i / 256)) for i in range(257)],
          comment="tanh over -4..4, Q15 in and out, 256 steps and a guard")
    table("i32", "decay", [round((1 << 30) * math.exp(-1 / (0.002 * 1000 ** (i / 127) * SR))) for i in range(128)], 8,
          comment="Per-sample decay, Q30: time constant 2 ms * 1000^(i/127)")
    table("u32", "lfo", [round(0.05 * 2 ** (v / 14) * 2 ** 32 / SR) for v in range(128)], 8,
          comment="LFO phase increment per sample for 0.05 Hz * 2^(v/14)")
    table("i16", "onepole", [round(32767 * (1 - math.exp(-2 * math.pi * min(40 * 2 ** (v / 12.7), SR * 0.45) / SR)))
                             for v in range(128)],
          comment="One-pole low-pass coefficient, Q15, cutoff 40 Hz * 2^(v/12.7)")
    table("u32", "exp2", [round(65536 * 2 ** (i / 256)) for i in range(257)],
          comment="2^(i/256), Q16")
    table("i32", "tangent", [round(65536 * math.tan(math.pi * min(20 * 1000 ** (i / 128), 0.45 * SR) / SR))
                             for i in range(129)], 10,
          comment="tan(pi fc / fs), Q16, fc = 20 Hz * 1000^(i/128), held at 0.45 fs")
    print("}}")


if __name__ == "__main__":
    main()
